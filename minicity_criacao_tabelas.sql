
-- ============================================================
-- 1. TABELA PESSOA
-- ============================================================

CREATE TABLE PESSOA (
    ID_PESSOA NUMBER(7) GENERATED BY DEFAULT AS IDENTITY,
    NM_PESSOA VARCHAR2(100) NOT NULL,
    DS_EMAIL VARCHAR2(120) NOT NULL,
    DS_PERFIL VARCHAR2(15),
    DT_CADASTRO DATE DEFAULT SYSDATE NOT NULL,
    DS_SENHA VARCHAR2(255) NOT NULL,

    CONSTRAINT PK_PESSOA PRIMARY KEY (ID_PESSOA),
    CONSTRAINT UK_PESSOA_EMAIL UNIQUE (DS_EMAIL),
    CONSTRAINT CK_PESSOA_PERFIL
        CHECK (DS_PERFIL IN ('MORADOR', 'TURISTA', 'NOVO_MORADOR'))
);

-- ============================================================
-- 2. TABELA CATEGORIA_OCORRENCIA
-- ============================================================

CREATE TABLE CATEGORIA_OCORRENCIA (
    ID_CATEGORIA NUMBER(3) GENERATED BY DEFAULT AS IDENTITY,
    NM_OCORRENCIA VARCHAR2(40) NOT NULL,
    DS_TEXTO VARCHAR2(200),

    CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UK_CATEGORIA_NOME UNIQUE (NM_OCORRENCIA)
);

-- ============================================================
-- 3. TABELA DISTRITO
-- ============================================================

CREATE TABLE DISTRITO (
    ID_DISTRITO NUMBER(5) GENERATED BY DEFAULT AS IDENTITY,
    NM_DISTRITO VARCHAR2(80) NOT NULL,
    DS_ZONA VARCHAR2(10) NOT NULL,
    DS_LATITUDE NUMBER(9,6) NOT NULL,
    DS_LONGITUDE NUMBER(9,6) NOT NULL,
    DS_TIPO_LOCALIDADE VARCHAR2(15),

    CONSTRAINT PK_DISTRITO PRIMARY KEY (ID_DISTRITO),
    CONSTRAINT UK_DISTRITO_NOME UNIQUE (NM_DISTRITO),

    CONSTRAINT CK_DISTRITO_ZONA
        CHECK (DS_ZONA IN ('CENTRO', 'NORTE', 'SUL', 'LESTE', 'OESTE')),

    CONSTRAINT CK_DISTRITO_LAT
        CHECK (DS_LATITUDE BETWEEN -90 AND 90),

    CONSTRAINT CK_DISTRITO_LON
        CHECK (DS_LONGITUDE BETWEEN -180 AND 180),

    CONSTRAINT CK_BAIRRO_TIPO
        CHECK (DS_TIPO_LOCALIDADE IN ('DISTRITO', 'BAIRRO', 'LOCALIDADE'))
);

-- ============================================================
-- 4. TABELA FONTE_DADO
-- ============================================================

CREATE TABLE FONTE_DADO (
    ID_FONTE NUMBER(4) GENERATED BY DEFAULT AS IDENTITY,
    NM_FONTE VARCHAR2(80) NOT NULL,
    DS_TIPO VARCHAR2(15) NOT NULL,
    DS_URL VARCHAR2(300) NOT NULL,

    CONSTRAINT PK_FONTE PRIMARY KEY (ID_FONTE),
    CONSTRAINT UK_FONTE_URL UNIQUE (DS_URL),

    CONSTRAINT CK_FONTE_TIPO
        CHECK (DS_TIPO IN ('API', 'PORTAL', 'TV', 'RADIO', 'ORGAO_PUBLICO'))
);

-- ============================================================
-- 5. TABELA OCORRENCIA
-- ============================================================

CREATE TABLE OCORRENCIA (
    ID_OCORRENCIA NUMBER(8) GENERATED BY DEFAULT AS IDENTITY,
    NM_TITULO VARCHAR2(120) NOT NULL,
    DS_OCORRENCIA VARCHAR2(2000),
    NR_GRAVIDADE NUMBER(1) NOT NULL,
    DS_ORIGEM VARCHAR2(10) NOT NULL,
    DS_STATUS VARCHAR2(15) DEFAULT 'ATIVA' NOT NULL,
    NR_LATITUDE NUMBER(9,6) NOT NULL,
    NR_LONGITUDE NUMBER(9,6) NOT NULL,
    DT_OCORRENCIA DATE NOT NULL,
    DT_PUBLICACAO DATE DEFAULT SYSDATE NOT NULL,
    DT_ATUALIZACAO DATE,
    ID_CATEGORIA NUMBER(3) NOT NULL,
    ID_FONTE NUMBER(4),
    ID_PESSOA NUMBER(7),
    ID_EXTERNO VARCHAR2(150),
    ID_DISTRITO NUMBER(5),

    CONSTRAINT PK_OCORRENCIA PRIMARY KEY (ID_OCORRENCIA),

    CONSTRAINT CK_OCORR_GRAVIDADE
        CHECK (NR_GRAVIDADE BETWEEN 1 AND 5),

    CONSTRAINT CK_OCORR_ORIGEM
        CHECK (DS_ORIGEM IN ('API', 'CIDADAO')),

    CONSTRAINT CK_OCORR_STATUS
        CHECK (DS_STATUS IN ('ATIVA', 'EM_ANALISE', 'RESOLVIDA', 'EXPIRADA')),

    CONSTRAINT CK_OCORR_LAT
        CHECK (NR_LATITUDE BETWEEN -90 AND 90),

    CONSTRAINT CK_OCORR_LON
        CHECK (NR_LONGITUDE BETWEEN -180 AND 180),

    CONSTRAINT CK_OCORR_ORIGEM_REF
        CHECK (
            (DS_ORIGEM = 'API' AND ID_FONTE IS NOT NULL AND ID_PESSOA IS NULL)
            OR
            (DS_ORIGEM = 'CIDADAO' AND ID_PESSOA IS NOT NULL AND ID_FONTE IS NULL)
        ),

    CONSTRAINT FK_OCORR_CATEGORIA
        FOREIGN KEY (ID_CATEGORIA)
        REFERENCES CATEGORIA_OCORRENCIA (ID_CATEGORIA),

    CONSTRAINT FK_OCORR_FONTE
        FOREIGN KEY (ID_FONTE)
        REFERENCES FONTE_DADO (ID_FONTE),

    CONSTRAINT FK_OCORR_PESSOA
        FOREIGN KEY (ID_PESSOA)
        REFERENCES PESSOA (ID_PESSOA),

    CONSTRAINT FK_OCORR_DISTRITO
        FOREIGN KEY (ID_DISTRITO)
        REFERENCES DISTRITO (ID_DISTRITO)
);

-- ============================================================
-- 6. TABELA COMENTARIO
-- ============================================================

CREATE TABLE COMENTARIO (
    ID_COMENTARIO NUMBER(8) GENERATED BY DEFAULT AS IDENTITY,
    DS_CONTEUDO VARCHAR2(500) NOT NULL,
    DT_PUBLICACAO DATE DEFAULT SYSDATE NOT NULL,
    ID_PESSOA NUMBER(7) NOT NULL,
    ID_DISTRITO NUMBER(5),
    ID_OCORRENCIA NUMBER(8),

    CONSTRAINT PK_COMENTARIO PRIMARY KEY (ID_COMENTARIO),

    CONSTRAINT FK_COMENT_PESSOA
        FOREIGN KEY (ID_PESSOA)
        REFERENCES PESSOA (ID_PESSOA),

    CONSTRAINT FK_COMENT_DISTRITO
        FOREIGN KEY (ID_DISTRITO)
        REFERENCES DISTRITO (ID_DISTRITO),

    CONSTRAINT FK_COMENT_OCORRENCIA
        FOREIGN KEY (ID_OCORRENCIA)
        REFERENCES OCORRENCIA (ID_OCORRENCIA)
);

